type ButtonProps = ButtonPrimitive.Props &
  VariantProps<typeof buttonVariants> & {
    /** Working: a spinner before the label, and the button cannot be pressed again. */
    loading?: boolean
  }

function Button({
  className,
  variant = "default",
  size = "default",
  loading = false,
  disabled,
  children,
  ...props
}: ButtonProps) {
  return (
    <ButtonPrimitive
      data-slot="button"
      data-loading={loading || undefined}
      aria-busy={loading || undefined}
      disabled={disabled || loading}
      className={cn(buttonVariants({ variant, size, className }))}
      {...props}
    >
      {loading && <Spinner aria-hidden data-icon="inline-start" />}
      {children}
    </ButtonPrimitive>
  )
}

/**
 * A link that looks like a button. Keeps link semantics (no role="button"), so pass the
 * link element through `render`: <ButtonLink render={<Link href="/skinlib" />}>….
 */
function ButtonLink({
  className,
  variant = "default",
  size = "default",
  render,
  ...props
}: useRender.ComponentProps<"a"> & VariantProps<typeof buttonVariants>) {
  return useRender({
    defaultTagName: "a",
    render,
    props: mergeProps<"a">({ className: cn(buttonVariants({ variant, size, className })) }, props),
    state: { slot: "button" },
  })
}

export { Button, ButtonLink, buttonVariants, type ButtonProps }
