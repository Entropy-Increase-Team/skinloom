/**
 * The icon a menu item names, at the navigation size. Without a known name it keeps an
 * empty box of the same size, so labels in a list still line up.
 */
export function MenuIcon({ name, className }: { name?: string | null; className?: string }) {
  const Icon = name ? menuIcons[name] : undefined
  if (!Icon) return <span data-slot="menu-icon" aria-hidden className={cn('inline-block size-4 shrink-0', className)} />
  return <Icon data-slot="menu-icon" aria-hidden className={cn('size-4 shrink-0', className)} />
}
