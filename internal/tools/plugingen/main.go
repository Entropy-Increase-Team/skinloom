func main() {
	check := flag.Bool("check", false, "verify generated files are up to date without writing")
	flag.Parse()

	root, err := findRepoRoot()
	if err != nil {
		fatalf("locate repo root: %v", err)
	}

	schemaPath := filepath.Join(root, "website", "static", "schema", "plugin.v1.json")
	catalogPath := filepath.Join(root, "web", "packages", "plugin-sdk", "src", "gen", "catalog.ts")

	schemaBytes, err := buildSchemaJSON()
	if err != nil {
		fatalf("build schema JSON: %v", err)
	}
	catalogBytes := []byte(buildTSCatalog())

	if *check {
		if err := assertUpToDate(schemaPath, schemaBytes); err != nil {
			fatalf("%v (run `go generate ./internal/plugin/...`)", err)
		}
		if err := assertUpToDate(catalogPath, catalogBytes); err != nil {
			fatalf("%v (run `go generate ./internal/plugin/...`)", err)
		}
		return
	}

	if err := writeGenerated(schemaPath, schemaBytes); err != nil {
		fatalf("write schema: %v", err)
	}
	if err := writeGenerated(catalogPath, catalogBytes); err != nil {
		fatalf("write TS catalog: %v", err)
	}
}

func findRepoRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", errors.New("go.mod not found")
		}
		dir = parent
	}
}

func writeGenerated(path string, content []byte) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, content, 0o644)
}

func assertUpToDate(path string, want []byte) error {
	got, err := os.ReadFile(path)
	if err != nil {
		return fmt.Errorf("read %s: %w", path, err)
	}
	if !bytes.Equal(normalizeLF(got), normalizeLF(want)) {
		return fmt.Errorf("%s is out of date", path)
	}
	return nil
}

func normalizeLF(b []byte) []byte {
	return bytes.ReplaceAll(b, []byte("\r\n"), []byte("\n"))
}

func fatalf(format string, args ...any) {
	_, _ = fmt.Fprintf(os.Stderr, "plugingen: "+format+"\n", args...)
	os.Exit(1)
}

