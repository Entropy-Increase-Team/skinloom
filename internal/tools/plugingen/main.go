func sortedPermissions() []string {
	all := plugin.AllPermissions()
	out := make([]string, 0, len(all))
	for k := range all {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

func buildTSCatalog() string {
	var b strings.Builder
	b.WriteString("// Code generated by internal/tools/plugingen; DO NOT EDIT.\n")
	b.WriteString("// Re-generate with: go generate ./internal/plugin/...\n\n")

	// Permissions
	permDefs := plugin.AllPermissions()
	permNames := sortedPermissions()
	b.WriteString("export type PluginRuntime = 'js' | 'native'\n\n")
	b.WriteString("export type PermissionRiskTier = 'normal' | 'sensitive' | 'high_risk'\n\n")
	b.WriteString("export type PluginPermission =\n")
	for _, p := range permNames {
		b.WriteString(fmt.Sprintf("  | '%s'\n", p))
	}
	b.WriteString("\nexport const PERMISSION_RISK: Record<PluginPermission, PermissionRiskTier> = {\n")
	for _, p := range permNames {
		b.WriteString(fmt.Sprintf("  '%s': '%s',\n", p, permDefs[p].Tier))
	}
	b.WriteString("} as const\n\n")
	b.WriteString("export const NATIVE_ONLY_PERMISSIONS: readonly PluginPermission[] = [\n")
	for _, p := range permNames {
		if permDefs[p].NativeOnly {
			b.WriteString(fmt.Sprintf("  '%s',\n", p))
		}
	}
	b.WriteString("] as const\n\n")

	// Struct types reflected from hook.Catalog()
	hooks := hook.Catalog()
	seenTypes := map[string]reflect.Type{}
	for _, h := range hooks {
		collectNamedTypes(h.Payload, seenTypes)
		if h.Value != nil {
			collectNamedTypes(h.Value, seenTypes)
		}
	}
	typeNames := make([]string, 0, len(seenTypes))
	for name := range seenTypes {
		typeNames = append(typeNames, name)
	}
	sort.Strings(typeNames)
	for _, name := range typeNames {
		emitTSInterface(&b, seenTypes[name])
	}

	// Hook maps (Guard / Filter / Event)
	var guards, filters, events []hook.Def
	for _, h := range hooks {
		switch h.Kind {
		case hook.KindGuard:
			guards = append(guards, h)
		case hook.KindFilter:
			filters = append(filters, h)
		case hook.KindEvent:
			events = append(events, h)
		}
	}

	b.WriteString("export interface HookGuardPayloads {\n")
	for _, g := range guards {
		b.WriteString(fmt.Sprintf("  '%s': %s\n", g.Name, goTypeToTS(g.Payload)))
	}
	b.WriteString("}\n\nexport type HookGuardName = keyof HookGuardPayloads\n\n")

	b.WriteString("export interface HookFilterDefinitions {\n")
	for _, f := range filters {
		b.WriteString(fmt.Sprintf("  '%s': { value: %s; context: %s }\n", f.Name, goTypeToTS(f.Value), goTypeToTS(f.Payload)))
	}
	b.WriteString("}\n\nexport type HookFilterName = keyof HookFilterDefinitions\n\n")

	b.WriteString("export interface HookEventPayloads {\n")
	for _, e := range events {
		b.WriteString(fmt.Sprintf("  '%s': %s\n", e.Name, goTypeToTS(e.Payload)))
	}
	b.WriteString("}\n\n")
	b.WriteString("export type HookEventName = keyof HookEventPayloads\n")
	b.WriteString("export type PluginCustomEventName = `plugin:${string}.${string}`\n\n")

	b.WriteString("export const HOOK_NAMES = {\n  guard: [\n")
	for _, g := range guards {
		b.WriteString(fmt.Sprintf("    '%s',\n", g.Name))
	}
	b.WriteString("  ] as const,\n  filter: [\n")
	for _, f := range filters {
		b.WriteString(fmt.Sprintf("    '%s',\n", f.Name))
	}
	b.WriteString("  ] as const,\n  event: [\n")
	for _, e := range events {
		b.WriteString(fmt.Sprintf("    '%s',\n", e.Name))
	}
	b.WriteString("  ] as const,\n} as const\n\n")

	// Slots
	b.WriteString("export interface PluginSlotProps {\n")
	for _, s := range plugin.Slots {
		if len(s.Props) == 0 {
			b.WriteString(fmt.Sprintf("  /** %s */\n  '%s': Record<string, never>\n", s.Description, s.Name))
			continue
		}
		b.WriteString(fmt.Sprintf("  /** %s */\n  '%s': {\n", s.Description, s.Name))
		for _, prop := range s.Props {
			opt := ""
			if prop.Optional {
				opt = "?"
			}
			b.WriteString(fmt.Sprintf("    %s%s: %s\n", prop.Name, opt, prop.TypeScript))
		}
		b.WriteString("  }\n")
	}
	b.WriteString("}\n\nexport type PluginSlotName = keyof PluginSlotProps\n")
	b.WriteString("export const PLUGIN_SLOTS: readonly PluginSlotName[] = [\n")
	for _, s := range plugin.Slots {
		b.WriteString(fmt.Sprintf("  '%s',\n", s.Name))
	}
	b.WriteString("] as const\n\n")

	// Built-in theme blocks
	b.WriteString("export interface BuiltinBlockPropsMap {\n")
	for _, blk := range theme.BlockTypes {
		if len(blk.Props) == 0 {
			b.WriteString(fmt.Sprintf("  '%s': Record<string, never>\n", blk.Type))
			continue
		}
		b.WriteString(fmt.Sprintf("  '%s': {\n", blk.Type))
		for _, prop := range blk.Props {
			b.WriteString(fmt.Sprintf("    %s?: %s\n", prop.Name, blockPropToTS(prop)))
		}
		b.WriteString("  }\n")
	}
	b.WriteString("}\n\nexport type BuiltinBlockType = keyof BuiltinBlockPropsMap\n\n")

	// Form scopes, setting types & theme overrides
	b.WriteString("export const FORM_SCOPES = [\n")
	for _, sc := range plugin.FormScopes {
		b.WriteString(fmt.Sprintf("  '%s',\n", sc))
	}
	b.WriteString("] as const\nexport type FormScope = (typeof FORM_SCOPES)[number]\n\n")

	b.WriteString("export const THEME_OVERRIDE_TARGETS = [\n")
	for _, ov := range plugin.ThemeOverrideTargets {
		b.WriteString(fmt.Sprintf("  '%s',\n", ov))
	}
	b.WriteString("] as const\nexport type ThemeOverrideTarget = (typeof THEME_OVERRIDE_TARGETS)[number]\n")

	return b.String()
}

func collectNamedTypes(t reflect.Type, dst map[string]reflect.Type) {
	if t == nil {
		return
	}
	for t.Kind() == reflect.Pointer || t.Kind() == reflect.Slice || t.Kind() == reflect.Array {
		t = t.Elem()
	}
	if t.Kind() == reflect.Map {
		collectNamedTypes(t.Elem(), dst)
		return
	}
	if t.Kind() != reflect.Struct || t.Name() == "" {
		return
	}
	if _, seen := dst[t.Name()]; seen {
		return
	}
	dst[t.Name()] = t
	for i := 0; i < t.NumField(); i++ {
		f := t.Field(i)
		if !f.IsExported() {
			continue
		}
		collectNamedTypes(f.Type, dst)
	}
}

func emitTSInterface(b *strings.Builder, t reflect.Type) {
	b.WriteString(fmt.Sprintf("export interface %s {\n", t.Name()))
	for i := 0; i < t.NumField(); i++ {
		f := t.Field(i)
		if !f.IsExported() {
			continue
		}
		tag := f.Tag.Get("json")
		if tag == "-" {
			continue
		}
		name, rest, _ := strings.Cut(tag, ",")
		if name == "" {
			name = f.Name
		}
		omitempty := strings.Contains(rest, "omitempty")
		opt := ""
		if omitempty {
			opt = "?"
		}
		b.WriteString(fmt.Sprintf("  %s%s: %s\n", name, opt, goTypeToTS(f.Type)))
	}
	b.WriteString("}\n\n")
}

func goTypeToTS(t reflect.Type) string {
	if t == nil {
		return "unknown"
	}
	switch t.Kind() {
	case reflect.Pointer:
		return goTypeToTS(t.Elem()) + " | null"
	case reflect.Slice, reflect.Array:
		return goTypeToTS(t.Elem()) + "[]"
	case reflect.Map:
		return fmt.Sprintf("Record<%s, %s>", goTypeToTS(t.Key()), goTypeToTS(t.Elem()))
	case reflect.String:
		return "string"
	case reflect.Bool:
		return "boolean"
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64,
		reflect.Float32, reflect.Float64:
		return "number"
	case reflect.Interface:
		return "unknown"
	case reflect.Struct:
		if t.Name() != "" {
			return t.Name()
		}
		return "Record<string, unknown>"
	default:
		return "unknown"
	}
}

func blockPropToTS(p theme.Prop) string {
	switch p.Type {
	case theme.PropText, theme.PropMarkdown:
		return "string | Record<string, string>"
	case theme.PropNumber:
		return "number"
	case theme.PropChoice:
		if len(p.Options) == 0 {
			return "string"
		}
		quoted := make([]string, len(p.Options))
		for i, o := range p.Options {
			quoted[i] = fmt.Sprintf("'%s'", o)
		}
		return strings.Join(quoted, " | ")
	case theme.PropButtons:
		return "Array<{ label: string | Record<string, string>; href: string }>"
	default:
		return "string"
	}
}
